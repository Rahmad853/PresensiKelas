import sqlite3
con = sqlite3.connect("db_absensi.db")
cur = con.cursor()
cur.execute("PRAGMA foreign_keys=OFF")
print("SEBELUM:", cur.execute("SELECT id,nama_kelas,angkatan FROM kelas ORDER BY id").fetchall())
cur.execute("DELETE FROM mahasiswa WHERE kelas_id NOT IN (2,3,4,5,6)")
cur.execute("DELETE FROM mata_kuliah WHERE kelas_id NOT IN (2,3,4,5,6)")
cur.execute("DELETE FROM users WHERE kelas_id NOT IN (2,3,4,5,6) AND id!=1 AND role!='mahasiswa'")
cur.execute("UPDATE users SET kelas_id=NULL WHERE role='mahasiswa'")
cur.execute("DELETE FROM kelas WHERE id NOT IN (2,3,4,5,6)")
cur.execute("UPDATE kelas SET angkatan=2025, tahun_ajaran=2025")
con.commit()
print("SESUDAH:", cur.execute("SELECT id,nama_kelas,angkatan FROM kelas ORDER BY id").fetchall())
con.close()
