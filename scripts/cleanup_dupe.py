import sqlite3
con = sqlite3.connect("db_absensi.db")
cur = con.cursor()
print("SEBELUM:", cur.execute("SELECT id, nama_kelas, angkatan FROM kelas ORDER BY id").fetchall())
cur.execute("PRAGMA foreign_keys=OFF")
cur.execute("DELETE FROM absensi WHERE nim IN (SELECT nim FROM mahasiswa WHERE kelas_id IN (7,8))")
cur.execute("DELETE FROM mahasiswa WHERE kelas_id IN (7,8)")
cur.execute("DELETE FROM mata_kuliah WHERE kelas_id IN (7,8)")
cur.execute("DELETE FROM users WHERE kelas_id IN (7,8)")
cur.execute("DELETE FROM qr_sessions WHERE kelas_id IN (7,8)")
cur.execute("DELETE FROM kelas WHERE id IN (7,8)")
con.commit()
print("SESUDAH:", cur.execute("SELECT id, nama_kelas, nama_ketua_kelas, angkatan FROM kelas ORDER BY id").fetchall())
con.close()
